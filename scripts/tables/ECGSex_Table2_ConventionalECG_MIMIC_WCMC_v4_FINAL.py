def norm(x):
    return re.sub(r"[^a-z0-9]+", "", str(x).lower())


def find_col(columns, candidates, label, required=True):
    exact = {norm(c): c for c in columns}
    for cand in candidates:
        key = norm(cand)
        if key in exact:
            return exact[key]

    for cand in candidates:
        key = norm(cand)
        hits = [c for c in columns if key in norm(c)]
        if len(hits) == 1:
            return hits[0]

    if required:
        raise RuntimeError(
            f"Could not identify {label}.\n"
            f"Candidates: {candidates}\n"
            f"Available columns:\n{list(columns)}"
        )
    return None


def mean_sd(x):
    x = pd.to_numeric(x, errors="coerce").dropna()
    if len(x) == 0:
        return "—"
    return f"{x.mean():.1f} ± {x.std(ddof=1):.1f}"


def fmt_delta(x):
    return f"{float(x):+.1f}"


def fmt_p(p):
    p = float(p)
    if not np.isfinite(p):
        return "—"
    if p < 0.001:
        return "P<0.001"
    return f"P={p:.3f}"


def exact_age_match(df, seed=42):
    d = df.copy()
    d["age_int"] = np.floor(pd.to_numeric(d["age"], errors="coerce"))
    d = d.dropna(subset=["age_int", "sex_binary"]).copy()
    d = d.loc[d["age_int"] >= 18].copy()
    d["age_int"] = d["age_int"].astype(int)

    rng = np.random.default_rng(seed)
    pieces = []

    for age, g in d.groupby("age_int", sort=True):
        female = g.loc[g["sex_binary"] == 0]
        male = g.loc[g["sex_binary"] == 1]
        n = min(len(female), len(male))
        if n == 0:
            continue

        f_idx = rng.choice(female.index.to_numpy(), size=n, replace=False)
        m_idx = rng.choice(male.index.to_numpy(), size=n, replace=False)

        pieces.append(d.loc[f_idx])
        pieces.append(d.loc[m_idx])

    if not pieces:
        raise RuntimeError("Age matching produced no participants.")

    out = pd.concat(pieces, ignore_index=True)

    nf = int((out["sex_binary"] == 0).sum())
    nm = int((out["sex_binary"] == 1).sum())
    if nf != nm:
        raise RuntimeError(f"Age match failed: female={nf:,}, male={nm:,}")

    return out


